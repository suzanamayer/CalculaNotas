# Programa que calcula a média aritmética de duas avaliações

# Entrada de dados
print()
print("Cálculo da média de duas avaliações")
print()
nota1 = float(input("Digite a nota da 1ª avaliação: "))
print()
nota2 = float(input("Digite a nota da 2ª avaliação: "))
print()

# Processamento
media = (nota1 + nota2) / 2

# Saída de dados
print(f"A média das duas avaliações é: {media:.2f}")
print()