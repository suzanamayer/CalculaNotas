# Programa que calcula a média aritmética de três avaliações

# Entrada de dados
print()
print("Cálculo da média de três avaliações")
print()
nota1 = float(input("Digite a nota da 1ª avaliação: "))
print()
nota2 = float(input("Digite a nota da 2ª avaliação: "))
print()
nota3 = float(input("Digite a nota da 3ª avaliação: "))
print()

# Processamento
media = (nota1 + nota2 + nota3) / 3

# Saída de dados
print(f"A média das três avaliações é: {media:.2f}")
print()